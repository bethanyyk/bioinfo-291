%% Watson's Test

function [U2] = watson_u2_test(alpha1, alpha2)
    % Inputs: alpha1, alpha2 in radians
   
    % Combine and sort samples
    n1 = length(alpha1);
    n2 = length(alpha2);
    N = n1 + n2;

    all_data = [alpha1; alpha2];
    [sorted_data, idx] = sort(all_data);

    group = [ones(n1,1); 2*ones(n2,1)];
    group = group(idx);

    % Empirical CDFs
    F1 = cumsum(group == 1) / n1 % Assembles i/n1, extending into 0s
    F2 = cumsum(group == 2) / n2; % Assembles j/n2, extending into 0s
    S1 = sum(F1 - F2);
    S2 = sum((F1 - F2).^2);
    U2 = (n1 * n2 / N^2) * (S2 - ((S1^2)/N));
end

